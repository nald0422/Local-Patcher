    class MyButtonHandler implements ActionListener {

        public void actionPerformed(ActionEvent e) {
            if (e.getSource().equals(sourceB)) {
                FileChooser(sourceTF);
            } else if (e.getSource().equals(destinationB)) {
                FileChooser(destinationTF);
            } else if (e.getSource().equals(pathB)) {
                pathSetting(sourceTF.getText(), destinationTF.getText());
                JOptionPane.showMessageDialog(null, "Successfully set");
                System.exit(0);
            }
        }
    }

    public void FileChooser(JTextField pathTarget) {
        fileChooser = new JFileChooser();
        fileChooser.setFileSelectionMode(JFileChooser.DIRECTORIES_ONLY);
        int returnValue = fileChooser.showOpenDialog(null);

        if (returnValue == JFileChooser.APPROVE_OPTION) {
            File selectedFile = fileChooser.getSelectedFile();
            path = selectedFile.getAbsolutePath();
            pathTarget.setText(path);
        } else if (returnValue == JFileChooser.CANCEL_OPTION) {
            System.out.println("File Explorer Cancelled");
        }
    }

    public void pathSetting(String source, String destination) {
        try {
            FileWriter filewriter = new FileWriter(filename);
            BufferedWriter bufferedWriter
                    = new BufferedWriter(filewriter);
            bufferedWriter.write(sourceTF.getText());
            bufferedWriter.newLine();
            bufferedWriter.write(destinationTF.getText());

            bufferedWriter.close();
        } catch (Exception ee) {
            ee.printStackTrace();
        }
    }
