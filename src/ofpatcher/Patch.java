    Thread t = new Thread() {
        @Override
        public void run() {
            while (true) {
                try {
                    FileReader fileReader
                            = new FileReader(filename);

                    BufferedReader bufferedReader
                            = new BufferedReader(fileReader);
                    String sourceLine = Files.readAllLines(Paths.get(filename)).get(0);
                    String destinationLine = Files.readAllLines(Paths.get(filename)).get(1);
                    line = bufferedReader.readLine();
                    bufferedReader.close();

                    System.out.print("Current Directories: ");
                    System.out.print("\t" + sourceLine + "\t\t" + destinationLine + "\n");

                    System.out.println("Timer task started at:" + new Date() + "\n");

                    File mainDirectory = new File(sourceLine);
                    File destinationDirectory = new File(destinationLine);

                    FileSearch.recursive(mainDirectory, destinationDirectory);

                } catch (IOException ex) {
                    Logger.getLogger(Patch.class.getName()).log(Level.SEVERE, null, ex);
                } catch (NoSuchAlgorithmException ex) {
                    Logger.getLogger(Patch.class.getName()).log(Level.SEVERE, null, ex);
                }
                System.out.println("\nTimer task finished at:" + new Date());
                try {
                    //1 hour 1000 * 60 * 60
                    Thread.sleep(1000 * 60 * 30);
                } catch (InterruptedException ex) {
                    Logger.getLogger(Patch.class.getName()).log(Level.SEVERE, null, ex);
                }
            }
        }
    };


